# ---- 2) 字符 2-gram TF-IDF 检索器（真实实现） -------------------------------
def ngrams(text, n=2):
    return {text[i:i + n] for i in range(len(text) - n + 1)}

class TfidfRetriever:
    """字符 2-gram TF-IDF 余弦检索：与神经网络编码器同理——先把文本变成向量，
    再按余弦相似度排序；TF-IDF 用词频加权替代语义，是检索实验的常用真实基线。"""

    def fit(self, corpus):
        df = {}
        for d in corpus:
            for g in ngrams(d):
                df[g] = df.get(g, 0) + 1
        self.vocab = {g: i for i, g in enumerate(df)}
        self.idf = np.array([np.log((len(corpus) + 1) / (df[g] + 1)) + 1
                             for g in self.vocab])
        self.M = np.zeros((len(corpus), len(self.vocab)))
        for i, d in enumerate(corpus):
            for g in ngrams(d):
                self.M[i, self.vocab[g]] += self.idf[self.vocab[g]]
        self.M /= np.linalg.norm(self.M, axis=1, keepdims=True) + 1e-12
        return self

    def search(self, query, k=5):
        q = np.zeros(len(self.vocab))
        for g in ngrams(query):
            if g in self.vocab:
                q[self.vocab[g]] += self.idf[self.vocab[g]]
        q /= np.linalg.norm(q) + 1e-12
        sims = self.M @ q
        return np.argsort(-sims)[:k]

def chunk(text, size, overlap=0.15):
    ov = int(size * overlap)
    step = max(size - ov, 1)
    return [text[i:i + size] for i in range(0, max(len(text) - ov, 1), step)]

# ---- 3) 不同 chunk 尺寸下跑完整检索实验 -------------------------------------
# 端到端指标：答案句完整落在一条块里（金块存在）且该块被召回进 top-3。
SIZES = [40, 48, 56, 64, 80, 96, 112, 128, 160, 192, 256]
gold_rate, r3 = [], []
avg_len = []
for size in SIZES:
    chunks = []                      # 全库切块
    gold = []                        # 每条问题的金块（块 id）或 None
    for di, (doc, q, ans) in enumerate(zip(DOCS, [p[1] for p in PAIRS],
                                           [p[2] for p in PAIRS])):
        cs = chunk(doc, size)
        base = len(chunks)
        chunks += cs
        gold.append(next((base + j for j, c in enumerate(cs)
                          if len(set(ans) & set(c)) / len(set(ans)) >= 0.85), None))
    retr = TfidfRetriever().fit(chunks)
    n_gold, n_hit = 0, 0
    for q, g in zip([p[1] for p in PAIRS], gold):
        if g is None:
            continue                 # 答案句被切碎：金块不存在，必然失败
        n_gold += 1
        n_hit += int(g in retr.search(q, k=3))
    gold_rate.append(n_gold / len(PAIRS))
    r3.append(n_hit / len(PAIRS))
    avg_len.append(np.mean([len(c) for c in chunks]))
    print(f"size={size:4d}  平均块长={avg_len[-1]:6.1f}  "
          f"金块存在率={gold_rate[-1]:.2f}  端到端R@3={r3[-1]:.2f}")

# ---- 4) 画图 ---------------------------------------------------------------
fig, ax = plt.subplots(figsize=(8.6, 5.2), dpi=150)
ax.plot(SIZES, gold_rate, "s--", color="#d62728", label="答案句完整率（切块质量）")
ax.plot(SIZES, r3, "o-", color="#1f77b4", label="端到端 Recall@3（完整且被召回）")
best = SIZES[int(np.argmax(r3))]
ax.axvline(best, color="gray", ls=":", lw=1.4)
ax.annotate(f"最佳平台自 {best} 字符起：\n再大召回持平，但单块信息密度下降、\n"
            "生成阶段要塞进更多无关文本",
            xy=(best, max(r3)), xytext=(best + 40, max(r3) - 0.30),
            fontsize=11, arrowprops=dict(arrowstyle="->"))
ax.set_xlabel("切块大小（字符，重叠 15%）")
ax.set_ylabel("比例（50 条文档-问题对）")
ax.set_ylim(0.85, 1.02)
ax.set_title("切块大小 vs 检索召回：太小把答案句切碎，召回骤降\n"
             "（真实实验：50 条“文档+问题”对，字符 2-gram TF-IDF 检索器）")
ax.grid(alpha=0.3)
ax.legend(loc="lower right")
fig.tight_layout()
fig.savefig(__file__.replace("gen_chunk_recall.py", "chunk_recall.png"),
            dpi=150, bbox_inches="tight")
